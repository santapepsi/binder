// Built-in demo catalog used when no Cardmática server is configured.
// Card texts are short summaries, not the printed card text.

import { ygoprodeckArtwork } from "../model/artworks.ts";
import type { CardSnapshot, PrintingRef } from "../model/types.ts";

interface DemoEntry {
  card: CardSnapshot;
  printings: PrintingRef[];
}

let next = 0;
function card(
  passcode: number,
  name: string,
  cardType: string,
  subtypes: string[],
  stats: Partial<CardSnapshot>,
  text: string,
  printings: [string, string, string][]
): DemoEntry {
  const id = `demo-${++next}`;
  return {
    card: {
      catalogId: id,
      ygoprodeckId: passcode,
      name,
      cardType,
      subtypes,
      attribute: null,
      level: null,
      rank: null,
      linkRating: null,
      pendulumScale: null,
      atk: null,
      def: null,
      pendulumText: null,
      imageUrl: null,
      thumbnailUrl: null,
      text,
      artworks: [ygoprodeckArtwork(passcode)],
      ...stats,
    },
    printings: printings.map(([code, setName, rarity]) => ({ id: `${id}-${code}`, code, setName, rarity })),
  };
}

